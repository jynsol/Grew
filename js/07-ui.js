  for(const t of treeBoxes){const overlap=Math.max(0,Math.min(b.right,t.right)-Math.max(b.left,t.left))*Math.max(0,Math.min(b.bottom,t.bottom)-Math.max(b.top,t.top))/area;occlusion+=Math.max(0,overlap-.12)}
