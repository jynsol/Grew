// Visitors are not guaranteed: each time a visit could happen we roll this chance. Every visitor
// milestone (completed works 1·6·10·15·20·25·30·40·50) raises it, from about 1 in 4 up to 4 in 5.
function forestVisitorChance() {
  const n = completedAll().length,
    steps = FOREST_VISITORS.filter((v) => n >= v.need).length;
  return steps ? Math.min(0.8, 0.2 + 0.065 * steps) : 0;
}

let forestVisitorBag = [],
  lastForestVisitor = "";

function nextForestVisitor() {
  const eligible = FOREST_VISITORS.filter((v) => completedAll().length >= v.need);
  forestVisitorBag = forestVisitorBag.filter((id) => eligible.some((v) => v.id === id));
  if (!forestVisitorBag.length) {
    forestVisitorBag = eligible.map((v) => v.id);
    for (let i = forestVisitorBag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [forestVisitorBag[i], forestVisitorBag[j]] = [forestVisitorBag[j], forestVisitorBag[i]];
    }
    if (forestVisitorBag.length > 1 && forestVisitorBag[0] === lastForestVisitor)
      [forestVisitorBag[0], forestVisitorBag[1]] = [forestVisitorBag[1], forestVisitorBag[0]];
  }
  lastForestVisitor = forestVisitorBag.shift() || "";
  return eligible.find((v) => v.id === lastForestVisitor);
}

function visitorPosition(cfg, boxes, scale, props = []) {
  const rx = cfg.boardW / 2 + 44,
    ry = cfg.boardH / 2 + 34;
  const candidates = [];
  // Include the entire animal and its animation travel in collision tests.
  for (let i = 0; i < 2400; i++) {
    const x = 360 + (Math.random() * 2 - 1) * rx,
      y = 286 + (Math.random() * 2 - 1) * ry;
    const r = { left: x - 52 * scale, right: x + 52 * scale, top: y - 65 * scale, bottom: y + 24 * scale };
    // Feet stay well inside the grass top; only the head may rise past the back edge.
    const inside = ([a, b], lim) => Math.abs(a - 360) / rx + Math.abs(b - 286) / ry < lim;
    if (
      !inside([x - 34 * scale, y + 10 * scale], 0.86) ||
      !inside([x + 34 * scale, y + 10 * scale], 0.86) ||
      !inside([x, y - 60 * scale], 1.1)
    )
      continue;
    // Only trunks and their base block a spot; an animal may stand in front of a crown.
    const feet = { left: x - 34 * scale, right: x + 34 * scale, top: y - 18 * scale, bottom: y + 14 * scale };
    // Wells, rocks, stumps and flowers are solid: the whole animal must stay clear of them.
    if (
      props.some(
        (b) =>
          x + 30 * scale > b.left - 4 &&
          x - 30 * scale < b.right + 4 &&
          y - 55 * scale < b.bottom + 4 &&
          y + 10 * scale > b.top - 4,
      )
    )
      continue;
    // The visitor is slotted in at its own depth among the trees, so only trunk bases block it.
    // ...but a tree in front may hide at most a third of it.
    const body = { left: x - 30 * scale, right: x + 30 * scale, top: y - 55 * scale, bottom: y },
      bodyArea = 60 * 55 * scale * scale;
    if (
      boxes.some(
        (b) =>
          b.bottom > y &&
          Math.max(0, Math.min(body.right, b.right) - Math.max(body.left, b.left)) *
            Math.max(0, Math.min(body.bottom, b.bottom) - Math.max(body.top, b.top)) >
            bodyArea / 3,
      )
    )
      continue;
    if (
      boxes.some((b) => {
        const base = b.bottom - (b.bottom - b.top) * 0.3;
        return (
          feet.left < b.right - (b.right - b.left) * 0.25 &&
          feet.right > b.left + (b.right - b.left) * 0.25 &&
          feet.top < b.bottom + 4 &&
          feet.bottom > base
        );
      })
    )
      continue;
    candidates.push({ x, y });
    if (candidates.length === 40) break;
  }
  return candidates[Math.floor(Math.random() * candidates.length)] || null;
}

