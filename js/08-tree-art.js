function treeSizeVariance(item) {
  const seed = (hash(String(item?.id || item?.title || "") + "|size") % 1000) / 1000;
  if (seed < 0.2) return 0.78 + (seed / 0.2) * 0.1;
  if (seed > 0.8) return 1.08 + ((seed - 0.8) / 0.2) * 0.2;
  return 0.92 + ((seed - 0.2) / 0.6) * 0.14;
}

