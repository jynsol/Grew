function treeArt(c, theme) {
  const growthItem = typeof c === "string" ? get(c) : c,
    growthKey = forestGrowthKey(growthItem);
  if (growthKey) return illustratedSpeciesArt(growthKey);
  const item = typeof c === "string" ? get(c) || {} : c,
    cat = category(item),
    sample = !Object.prototype.hasOwnProperty.call(item || {}, "genre") && !item?.id && item?.treeCategory;
  if (item?.hiddenTree === "A" || item?.hiddenTree === "B") return hiddenTreeArt(item.hiddenTree, theme);
  if (theme === "snow" || theme === "winter") return snowTreeArt(item);
  const species = sample ? speciesForCategory(cat.id)[0] : contentSpecies(item);
  return speciesArt(species?.id || TREE_SPECIES[0].id, theme);
}

